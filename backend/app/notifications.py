def send_intervention_email(guardian_email: str, guardian_name: str, student_name: str, language: str, action: str, notes: str):
    """
    Dispatches a real email via Resend API using the preferred multilingual template.
    """
    lang = language if language in TEMPLATES else "en"
    template = TEMPLATES[lang]
    
    subject = template["subject"].format(student_name=student_name)
    html_body = template["html"].format(
        guardian_name=guardian_name,
        student_name=student_name,
        action=action,
        notes=notes
    )
    
    # In sandbox mode without a real key, we mock the dispatch.
    if resend.api_key.startswith("re_123456"):
        print(f"--- [SANDBOX MODE] Mock Email Dispatch ---")
        print(f"To: {guardian_email}")
        print(f"Subject: {subject}")
        print(f"Body: {html_body[:100]}...")
        return {"id": "sandbox_msg_id", "status": "mocked"}

    try:
        r = resend.Emails.send({
            "from": "Academics <onboarding@resend.dev>",
            "to": [guardian_email],
            "subject": subject,
            "html": html_body
        })
        print(f"Email sent successfully to {guardian_email}: {r}")
        return r
    except Exception as e:
        print(f"Failed to send email via Resend: {e}")
        return None
